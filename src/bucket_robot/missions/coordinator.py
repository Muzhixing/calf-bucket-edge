"""Build the existing mission worker command; runtime.application owns its lifecycle."""

import sys


def command(layout, out, port, budget, *, execute_post_geometry=False, resume_post_plan=None):
    if resume_post_plan:
        return [
            sys.executable,
            "-m",
            "bucket_robot",
            "post",
            "--plan",
            str(resume_post_plan),
            "--reference",
            str(layout.config / "arm_reference.json"),
            "--out",
            str(out / "mission"),
        ]
    return [
        sys.executable,
        "-m",
        "bucket_robot",
        "forward",
        "--recover-loss",
        "--distance-first",
        "--cruise-speed",
        "20",
        "--track-b",
        "--post-approach-plan",
        *(["--execute-post-geometry"] if execute_post_geometry else []),
        "--reference",
        str(layout.config / "arm_reference.json"),
        "--left-reference",
        str(layout.config / "left_view_reference.json"),
        "--calibration",
        str(layout.assets / "calibration.yml"),
        "--approach-model",
        str(layout.assets / "fast_acv.rknn"),
        "--approach-calibration",
        str(layout.assets / "calibration.json"),
        "--approach-surface-band",
        ".35",
        ".78",
        ".65",
        ".95",
        "--out",
        str(out / "mission"),
        "--auto-target",
        "--expect-a",
        "73",
        "--expect-b",
        "0",
        "--seconds",
        str(budget),
        "--until-left",
        "--bearing-tracker",
        "--native-port",
        str(port),
    ]
